# ============================================================
# Region 标准化
# ============================================================

def normalize_region(
    region: str
):

    """
    将用户输入地区标准化。

    例如：

    广东省
        ↓
    广东

    上海市
        ↓
    上海
    """


    if not region:

        return ""


    region = region.strip()


    # --------------------------------------------------------
    # 全国范围
    # --------------------------------------------------------

    if region in {

        "中国",
        "全国",
        "全国范围",

    }:

        return "中国"



    # --------------------------------------------------------
    # 去除行政区后缀
    # --------------------------------------------------------

    suffixes = [

        "壮族自治区",
        "回族自治区",
        "维吾尔自治区",
        "特别行政区",
        "自治区",
        "省",
        "市",

    ]


    for suffix in suffixes:

        if region.endswith(
            suffix
        ):

            region = region[
                :-len(suffix)
            ]

            break


    return region



# ============================================================
# Industry匹配
# ============================================================

def match_industry(
    query_industry: str,
    company_industry: str
):

    """
    简单行业模糊匹配。

    例如：

    汽车零部件

    可以匹配：

    汽车零部件
    新能源汽车零部件
    """


    if not query_industry:

        return True


    query_industry = (
        query_industry.strip()
    )


    company_industry = (
        company_industry.strip()
    )


    return (

        query_industry
        in company_industry

        or

        company_industry
        in query_industry

    )



# ============================================================
# 企业搜索
# ============================================================

@tool
def search_companies(
    industry: str,
    region: str,
):

    """
    根据行业和地区搜索潜在企业。

    Args:
        industry:
            目标行业。

            例如：
            汽车零部件
            新能源汽车零部件

        region:
            目标地区。

            例如：
            中国
            江苏
            广东
            浙江

    Returns:
        符合条件的企业列表。
    """


    normalized_region = (
        normalize_region(
            region
        )
    )


    results = []


    # ========================================================
    # 遍历Mock企业数据库
    # ========================================================

    for company in MOCK_COMPANIES:


        # ----------------------------------------------------
        # Industry过滤
        # ----------------------------------------------------

        industry_match = match_industry(

            industry,

            company["industry"]

        )


        if not industry_match:

            continue



        # ----------------------------------------------------
        # Region过滤
        # ----------------------------------------------------

        if normalized_region == "中国":

            region_match = True

        else:

            region_match = (

                normalize_region(
                    company["region"]
                )

                ==

                normalized_region

            )


        if not region_match:

            continue



        # ----------------------------------------------------
        # 加入搜索结果
        # ----------------------------------------------------

        results.append(
            company.copy()
        )



    # ========================================================
    # 控制Mock数据一次返回数量
    # ========================================================
    #
    # 当前SalesGoal通常target_count=3。
    #
    # 全国搜索时没有必要一次把所有Mock企业全部返回，
    # 否则会产生：
    #
    # - 大量News查询
    # - 大量Jobs查询
    # - Reviewer处理过多企业
    # - Token消耗增加
    #
    # 所以Mock阶段最多返回3家。
    #
    # 指定单独地区时通常只返回该地区企业。
    # ========================================================

    if normalized_region == "中国":

        results = results[:3]



    return results




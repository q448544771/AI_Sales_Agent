from app.database.db import SessionLocal
from app.database.models import Lead


# ============================================================
# 根据销售阶段生成默认 Follow-up Action
# ============================================================

def generate_followup_action(
    stage: str,
    score: float = 0.0,
    evidence: str = ""
):

    """
    根据CRM销售阶段生成默认跟进动作。

    注意：

    这里生成的是 fallback action。

    只有当数据库中没有 next_action 时，
    才会使用这里的默认规则。

    如果 Executor / LLM 已经生成了更具体的
    next_action，则保留原有内容。
    """


    # ========================================================
    # New
    # ========================================================

    if stage == "new":

        return (
            "收集企业基础信息，确认产品类型、生产工艺以及当前质量检测方式，"
            "寻找质量部门、自动化部门或智能制造负责人。"
        )


    # ========================================================
    # Contacted
    # ========================================================

    if stage == "contacted":

        return (
            "7天内进行二次跟进，确认客户当前检测痛点、预算周期以及项目推进计划。"
        )


    # ========================================================
    # Qualified
    # ========================================================

    if stage == "qualified":

        return (
            "48小时内联系客户技术负责人，围绕自动化产线和视觉质检需求开展技术交流，"
            "准备行业案例和POC验证方案。"
        )


    # ========================================================
    # Meeting
    # ========================================================

    if stage == "meeting":

        return (
            "准备技术方案和报价，进一步确认检测目标、产品节拍、缺陷类型以及部署环境。"
        )


    # ========================================================
    # Proposal
    # ========================================================

    if stage == "proposal":

        return (
            "跟进技术方案与报价反馈，确认客户对检测指标、实施周期、预算及商务条款的意见，"
            "推动方案确认。"
        )


    # ========================================================
    # Negotiation
    # ========================================================

    if stage == "negotiation":

        return (
            "持续推进商务谈判，确认最终价格、交付周期、验收标准及合同条款，"
            "推动项目进入签约阶段。"
        )


    # ========================================================
    # Won
    # ========================================================

    if stage == "won":

        return (
            "进入项目交付与客户成功阶段，跟踪实施进度、验收结果及后续追加需求。"
        )


    # ========================================================
    # Lost
    # ========================================================

    if stage == "lost":

        return (
            "记录丢单原因并归档，分析价格、技术、竞争对手或项目取消等因素，"
            "保留后续重新激活机会。"
        )


    # ========================================================
    # 未知阶段
    # ========================================================

    return (
        "持续跟踪客户业务变化，监控新增产线、招聘、采购及质量升级信号。"
    )



# ============================================================
# Follow-up Node
# ============================================================

def followup_node(state):

    """
    为CRM客户维护下一步销售动作。


    核心原则：

    1. 如果客户已经存在 next_action：
       保留已有内容，不覆盖。


    2. 如果客户没有 next_action：
       根据 stage 自动生成默认动作。


    因此：

    Executor / LLM
        ↓
    生成个性化 next_action
        ↓
    update_lead_stage()
        ↓
    数据库存储
        ↓
    Follow-up Node
        ↓
    发现已有 next_action
        ↓
    保留

    不再被固定规则覆盖。
    """


    db = SessionLocal()


    updated_count = 0
    preserved_count = 0


    try:

        # ====================================================
        # 查询全部CRM客户
        # ====================================================

        leads = (
            db.query(Lead)
            .all()
        )


        # ====================================================
        # 遍历客户
        # ====================================================

        for lead in leads:


            # =================================================
            # 已经有 next_action
            # =================================================
            #
            # Executor可能已经根据：
            #
            # 新闻
            # 招聘
            # CRM历史
            # Buying Signals
            #
            # 生成了更详细的销售动作。
            #
            # 此时Follow-up Node不能覆盖。
            # =================================================

            if (
                lead.next_action
                and
                lead.next_action.strip()
            ):

                preserved_count += 1


                print(
                    f"保留已有跟进动作: "
                    f"{lead.company}"
                )


                continue


            # =================================================
            # 没有 next_action
            # =================================================
            #
            # 才使用规则生成fallback action。
            # =================================================

            next_action = generate_followup_action(

                stage=lead.stage or "new",

                score=lead.score or 0.0,

                evidence=lead.evidence or ""

            )


            # =================================================
            # 保存生成结果
            # =================================================

            lead.next_action = next_action


            updated_count += 1


            print(
                f"生成默认跟进动作: "
                f"{lead.company}"
            )


        # ====================================================
        # 提交数据库
        # ====================================================

        db.commit()


        # ====================================================
        # 调试日志
        # ====================================================

        print(
            "\n===== Follow-up Summary ====="
        )


        print(
            f"新生成动作: {updated_count}"
        )


        print(
            f"保留已有动作: {preserved_count}"
        )


        # ====================================================
        # 返回LangGraph State
        # ====================================================

        return {

            "followup_updated":
                updated_count,

            "status":
                "followup_completed"

        }


    except Exception:

        # ====================================================
        # 出错回滚
        # ====================================================

        db.rollback()

        raise


    finally:

        # ====================================================
        # 关闭数据库连接
        # ====================================================

        db.close()
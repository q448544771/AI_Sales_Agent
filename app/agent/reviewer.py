# ============================================================
# 格式化产品知识库
# ============================================================

def format_knowledge_context(
    knowledge_context
):

    """
    将RAG检索结果转换为Prompt文本。

    同时保留source信息，
    方便Reviewer明确哪些内容真正来自内部知识库。
    """


    if not knowledge_context:

        return "暂无产品知识"


    texts = []


    seen_contents = set()


    for item in knowledge_context:


        if not isinstance(
            item,
            dict
        ):

            continue


        content = (

            item.get(
                "content",
                ""
            )

            or

            ""

        ).strip()


        source = (

            item.get(
                "source",
                ""
            )

            or

            "未知来源"

        )


        if not content:

            continue


        # 防止同一个知识片段重复进入Prompt
        if content in seen_contents:

            continue


        seen_contents.add(
            content
        )


        texts.append(

            f"""
【知识来源】
{source}

【知识内容】
{content}
""".strip()

        )


    if not texts:

        return "暂无产品知识"


    return "\n\n".join(
        texts
    )



# ============================================================
# 清理JSON文本
# ============================================================

def clean_json_content(
    content
):

    """
    清理模型可能返回的Markdown JSON代码块。

    正常情况下Reviewer已经被要求只输出JSON，
    这里作为解析层兜底。
    """


    content = (
        content
        or
        ""
    ).strip()


    if content.startswith(
        "```json"
    ):

        content = content[
            len("```json"):
        ].strip()


    elif content.startswith(
        "```"
    ):

        content = content[
            len("```"):
        ].strip()


    if content.endswith(
        "```"
    ):

        content = content[
            :-3
        ].strip()


    return content



# ============================================================
# Reviewer Node
# ============================================================

def review_node(
    state
):

    """
    Reviewer Node


    对Executor收集到的企业信息进行评估，

    并结合固定RAG Knowledge Retrieval Node
    写入的knowledge_context，

    输出Top 3潜在客户。


    输入：

        messages

        knowledge_context


    输出：

        candidate_leads
    """


    llm = (
        get_reasoning_llm()
    )


    # ========================================================
    # 企业调查记录
    # ========================================================

    messages = state.get(
        "messages",
        []
    )


    # ========================================================
    # 获取产品知识
    # ========================================================

    knowledge_context = state.get(
        "knowledge_context",
        []
    )


    product_knowledge = (
        format_knowledge_context(
            knowledge_context
        )
    )


    # ========================================================
    # Reviewer Prompt
    # ========================================================

    prompt = f"""

你是一名B2B工业销售分析专家。


你的任务是：

根据企业调研信息，

结合企业内部产品知识库，

判断哪些企业近期最可能存在
工业机器视觉质检方案的销售机会。


你必须严格区分：

企业事实

产品知识

销售推断

待确认事项。



============================================================
产品知识库
============================================================

{product_knowledge}



============================================================
企业调查记录
============================================================

{messages}



============================================================
Reviewer可靠性规则
============================================================

{REVIEWER_RELIABILITY_RULES}



============================================================
任务要求
============================================================


1.

找出真正具有购买潜力的企业。


购买潜力必须主要来自企业证据，

例如：

- 新建工厂
- 扩建生产线
- 自动化升级
- 智能制造改造
- 机器视觉岗位招聘
- 质量检测能力升级


不能因为产品知识库存在某种能力，

就推断所有企业都需要该能力。



2.

根据企业事实评估：

purchase_intent_score


范围：

0 - 1


评分越高，

代表近期出现的购买信号越强。


评分不能仅由产品匹配度决定。



3.

opportunity_level

用于描述当前销售机会等级。


推荐使用：

- 高
- 中
- 低


不要使用：

- 最高
- 极高
- TOP
- S级
- T1

等非标准CRM等级描述。



4.

evidence

必须只包含：

企业调查记录中明确出现的事实。


不要把：

产品知识
模型推断
推荐方案

写入evidence。



5.

solution_match

必须说明：

企业的实际需求信号

与

内部产品知识库明确支持能力

之间的对应关系。


例如：

企业：

升级表面缺陷检测能力


知识库：

外观缺陷检测
支持划痕、凹坑、毛刺、污渍


可以写：

“企业表面缺陷检测升级需求，
与知识库明确支持的外观缺陷检测能力匹配。”


如果具体缺陷类型没有企业证据，

不要自行假设企业一定存在某种缺陷。



6.

recommended_action

必须给出：

下一步真实销售动作。


应该优先包含：

- 联系谁
- 确认什么
- 准备什么知识库已支持的方案
- 哪些指标需要POC验证
- 哪些数据需要后续ROI测算


不得：

- 虚构已有ROI
- 虚构已有客户案例
- 虚构已有POC结果
- 虚构技术指标
- 仅根据招聘或公开情报建议升级CRM stage



7.

最多输出Top 3潜在客户。


如果真正符合条件的企业不足3家，

可以少于3家。



============================================================
输出格式
============================================================


请严格输出JSON数组。


禁止输出：

Markdown

解释文字

代码块

前言

总结


只允许输出JSON。


格式：


[

    {{

        "company": "",

        "purchase_intent_score": 0.0,

        "opportunity_level": "",

        "evidence": [],

        "solution_match": [],

        "recommended_action": ""

    }}

]


============================================================
最终检查
============================================================

输出前逐项检查：


1.

evidence是否全部来自企业事实？


2.

solution_match中的产品能力
是否全部来自产品知识库？


3.

是否把知识库没有的：

ROI
案例
指标
认证
POC结果

写成已有事实？


如果有，

必须删除或改成：

“待确认”
“后续测算”
“POC验证”。


4.

是否因为招聘信息
直接建议推进CRM stage？


如果有，

必须删除。


5.

recommended_action是否属于未来可执行动作，

而不是虚构已经发生的销售进展？


全部满足后，

再输出JSON。

"""


    # ========================================================
    # 调用Reviewer LLM
    # ========================================================

    response = llm.invoke(
        prompt
    )


    content = clean_json_content(
        response.content
    )


    # ========================================================
    # JSON解析
    # ========================================================

    try:

        data = json.loads(
            content
        )


    except Exception as e:


        print(
            "Reviewer JSON解析失败:"
        )


        print(
            content
        )


        raise e


    # ========================================================
    # 基础结构检查
    # ========================================================

    if not isinstance(
        data,
        list
    ):

        raise ValueError(
            "Reviewer输出必须是JSON数组"
        )


    # ========================================================
    # 最多Top 3
    # ========================================================

    data = data[:3]


    # ========================================================
    # Pydantic校验
    # ========================================================

    leads = []


    for item in data:


        result = LeadAssessment(
            **item
        )


        leads.append(
            result.model_dump()
        )


    print(
        f"Reviewer发现 {len(leads)} 个潜在客户"
    )


    return {

        "candidate_leads":
            leads,

        "status":
            "reviewed",

    }